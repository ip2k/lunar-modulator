typedef struct fm1_resampler {
  int64_t step;       /* input samples per intermediate sample, 32.32 fixed point */
  int64_t lead;       /* step + the kernel's reach + 1: input an output needs past rel */
  int64_t rel;        /* next intermediate sample's input position less the inputs
                         received so far, 32.32 (at or below zero once fed) */
  uint32_t tap_step;  /* kernel table entries per input sample, 16.16 */
  float gain;         /* intermediate samples per input sample (rho) */
  uint32_t mode;      /* FM1_RESAMPLER_OFF, _PASS or _CONVERT */
  uint32_t held;      /* pass-through: in[0] holds a sample not yet popped */
  uint32_t in_w, mid_w;   /* next write slot of each ring */
  uint32_t poly;      /* 1: the 51/47 fast path (rel and lead in whole inputs, mid unused) */
  uint32_t poly_q;    /* its next output's phase, 0 .. 46 */
  /* Rings, each written twice (at w and w + CAP) so any window of CAP
   * consecutive samples is contiguous. */
  float in[2 * FM1_RESAMPLER_IN_CAP];
  float mid[2 * FM1_RESAMPLER_MID_CAP];   /* the last 123 intermediate samples */
} fm1_resampler_t;

/* Sets r up to convert in_rate to out_rate. Returns 1, or 0 (r then passes
 * nothing: needed() is 0 and pop() returns 0) when the ratio
 * in_rate / out_rate is outside 1..FM1_RESAMPLER_MAX_RATIO or either rate is
 * not a positive finite number. */
static inline int fm1_resampler_init(fm1_resampler_t *r, float in_rate, float out_rate) {
  uint32_t i;
  double ratio, rho;
  r->step = r->lead = r->rel = 0;
  r->tap_step = 0;
  r->gain = 0.0f;
  r->mode = FM1_RESAMPLER_OFF;
  r->held = 0;
  r->in_w = r->mid_w = 0;
  r->poly = r->poly_q = 0;
  for (i = 0; i < 2 * FM1_RESAMPLER_IN_CAP; ++i) r->in[i] = 0.0f;
  for (i = 0; i < 2 * FM1_RESAMPLER_MID_CAP; ++i) r->mid[i] = 0.0f;
  if (!(in_rate > 0.0f && out_rate > 0.0f && in_rate < 1e30f && out_rate < 1e30f)) return 0;
  ratio = (double)in_rate / (double)out_rate;
  if (in_rate == out_rate) {
    r->mode = FM1_RESAMPLER_PASS;
    return 1;
  }
  if (!(ratio >= 1.0 && ratio <= FM1_RESAMPLER_MAX_RATIO)) return 0;
#if FM1_RESAMPLER_POLY47
  {
    /* 51/47 within 10 ppm: Plaits' 47,872.34 Hz to 44,118 Hz is -7.9 ppm. */
    const double off = ratio * FM1_RESAMPLER_POLY47_PHASES / FM1_RESAMPLER_POLY47_STEP - 1.0;
    if (off < 1e-5 && off > -1e-5) {
      r->mode = FM1_RESAMPLER_CONVERT;
      r->poly = 1;
      r->gain = 1.0f;
      /* Output 0 is input time 0: its 48 inputs start 23 before input 0
       * (zeros), so it needs inputs 0 .. 24. rel is the next output's first
       * input less the inputs received, lead the 48 it reads, both whole. */
      r->rel = -((int64_t)FM1_RESAMPLER_POLY47_CENTRE << 32);
      r->lead = (int64_t)FM1_RESAMPLER_POLY47_TAPS << 32;
      return 1;
    }
  }
#endif
  rho = 2.0 / ratio;                 /* in [0.5, 2] */
  r->mode = FM1_RESAMPLER_CONVERT;
  r->gain = (float)rho;
  r->step = (int64_t)(ratio / 2.0 * 4294967296.0 + 0.5);
  r->tap_step = (uint32_t)(rho * FM1_RESAMPLER_PHASES * 65536.0 + 0.5);
  /* The kernel reaches SPAN / 2 intermediate samples, SPAN / (2 rho) input
   * samples, either side; one input more covers the rounding of tap_step. */
  r->lead = r->step + (int64_t)(FM1_RESAMPLER_SPAN / (2.0 * rho) * 4294967296.0 + 0.5) +
            ((int64_t)1 << 32);
  return 1;
}

/* Input samples r must receive before the next fm1_resampler_pop. */
static inline uint32_t fm1_resampler_needed(const fm1_resampler_t *r) {
  int64_t v;
  if (r->mode != FM1_RESAMPLER_CONVERT) return r->mode == FM1_RESAMPLER_PASS && !r->held;
  v = r->rel + r->lead;
  return v > 0 ? (uint32_t)(((uint64_t)v + 0xFFFFFFFFu) >> 32) : 0u;
}

/* Takes up to n samples, never more than fm1_resampler_needed(r); returns
 * how many it took. */
static inline uint32_t fm1_resampler_push(fm1_resampler_t *r, const float *in, uint32_t n) {
  uint32_t i, need = fm1_resampler_needed(r);
  if (n > need) n = need;
  if (r->mode != FM1_RESAMPLER_CONVERT) {
    if (n) { r->in[0] = in[0]; r->held = 1; }
    return n;
  }
  for (i = 0; i < n; ++i) {
    r->in[r->in_w] = r->in[r->in_w + FM1_RESAMPLER_IN_CAP] = in[i];
    if (++r->in_w == FM1_RESAMPLER_IN_CAP) r->in_w = 0;
  }
  r->rel -= (int64_t)n << 32;
  return n;
}

/* The kernel at table position t (16.16), linearly interpolated. */
static inline float fm1_resampler_tap_(uint32_t t) {
  const float *k = &fm1_resampler_kernel[t >> 16];
  return k[0] + (float)(t & 0xFFFFu) * (1.0f / 65536.0f) * (k[1] - k[0]);
}

/* One intermediate sample at input position rel (relative to the inputs
 * received): the sum of x[n] k((P - n) rho) over the inputs the kernel
 * reaches. The taps at or before P walk the half table outwards one way,
 * the later ones the other; two sums, so the two chains overlap. */
static inline float fm1_resampler_intermediate_(fm1_resampler_t *r) {
  const uint32_t ts = r->tap_step;
  const uint32_t end = (uint32_t)(FM1_RESAMPLER_KERNEL_LEN - 1) << 16;
  const int64_t rel = r->rel;
  const uint32_t frac = (uint32_t)((uint64_t)rel & 0xFFFFFFFFu);
  /* The input at floor(P): the newest input is at in_w - 1 + CAP. */
  const float *before = &r->in[r->in_w + FM1_RESAMPLER_IN_CAP - 1] + (rel >> 32) + 1;
  const float *after = before + 1;
  uint32_t tb = (uint32_t)(((uint64_t)frac * ts) >> 32);
  uint32_t ta = (uint32_t)((((uint64_t)1 << 32) - frac) * ts >> 32);
  float sb = 0.0f, sa = 0.0f;
  for (; tb < end && ta < end; tb += ts, ta += ts, --before, ++after) {
    sb += fm1_resampler_tap_(tb) * *before;
    sa += fm1_resampler_tap_(ta) * *after;
  }
  for (; tb < end; tb += ts, --before) sb += fm1_resampler_tap_(tb) * *before;
  for (; ta < end; ta += ts, ++after) sa += fm1_resampler_tap_(ta) * *after;
  r->rel = rel + r->step;
  return (sb + sa) * r->gain;
}

#if FM1_RESAMPLER_POLY47
/* The 51/47 fast path's next output, once its 48 inputs are in: row q (or
 * row 47 - q backwards) against them, over four sums so their chains
 * overlap; then the next phase, q + 4 (51 = 47 + 4), and one input on, or
 * two when the phase wraps. */
static inline float fm1_resampler_poly47_(fm1_resampler_t *r) {
  const uint32_t q = r->poly_q;
  /* rel is -48 here: the first of the newest 48 inputs. */
  const float *x = &r->in[r->in_w + FM1_RESAMPLER_IN_CAP] + (r->rel >> 32);
  float a0 = 0.0f, a1 = 0.0f, a2 = 0.0f, a3 = 0.0f;
  uint32_t k, next = q + (FM1_RESAMPLER_POLY47_STEP - FM1_RESAMPLER_POLY47_PHASES);
  if (q < FM1_RESAMPLER_POLY47_ROWS) {
    const float *c = fm1_resampler_poly47[q];
    for (k = 0; k < FM1_RESAMPLER_POLY47_TAPS; k += 4) {
      a0 += c[k] * x[k];
      a1 += c[k + 1] * x[k + 1];
      a2 += c[k + 2] * x[k + 2];
      a3 += c[k + 3] * x[k + 3];
    }
  } else {
    const float *c = &fm1_resampler_poly47[FM1_RESAMPLER_POLY47_PHASES - q]
                                          [FM1_RESAMPLER_POLY47_TAPS - 1];
    for (k = 0; k < FM1_RESAMPLER_POLY47_TAPS; k += 4) {
      a0 += c[-(int32_t)k] * x[k];
      a1 += c[-(int32_t)k - 1] * x[k + 1];
      a2 += c[-(int32_t)k - 2] * x[k + 2];
      a3 += c[-(int32_t)k - 3] * x[k + 3];
    }
  }
  if (next >= FM1_RESAMPLER_POLY47_PHASES) {
    r->poly_q = next - FM1_RESAMPLER_POLY47_PHASES;
    r->rel += (int64_t)2 << 32;
  } else {
    r->poly_q = next;
    r->rel += (int64_t)1 << 32;
  }
  return (a0 + a1) + (a2 + a3);
}
#endif

/* The next output sample. Returns 0 and changes nothing if r still needs
 * input (fm1_resampler_needed > 0). */
static inline float fm1_resampler_pop(fm1_resampler_t *r) {
  const float *h = fm1_resampler_lowpass, *e;
  float y0 = 0.0f, y1 = 0.0f, y2 = 0.0f, y3 = 0.0f;
  uint32_t j;
  if (r->mode != FM1_RESAMPLER_CONVERT) {
    if (!r->held) return 0.0f;
    r->held = 0;
    return r->in[0];
  }
  if (fm1_resampler_needed(r)) return 0.0f;
#if FM1_RESAMPLER_POLY47
  if (r->poly) return fm1_resampler_poly47_(r);
#endif
  for (j = 0; j < 2; ++j) {             /* intermediate samples 2k and 2k + 1 */
    const float x = fm1_resampler_intermediate_(r);
    r->mid[r->mid_w] = r->mid[r->mid_w + FM1_RESAMPLER_MID_CAP] = x;
    if (++r->mid_w == FM1_RESAMPLER_MID_CAP) r->mid_w = 0;
  }
  /* Output k is the low-pass centred on intermediate sample 2k - 60, the
   * middle of the last 123 (2k - 121 .. 2k + 1, oldest at e[0]); the pairs
   * from the outside in, over four sums so their chains overlap. */
  e = &r->mid[r->mid_w];
  for (j = 0; j + 4 <= FM1_RESAMPLER_LP_PAIRS; j += 4) {
    y0 += h[j] * (e[j] + e[FM1_RESAMPLER_LP_LEN - 1 - j]);
    y1 += h[j + 1] * (e[j + 1] + e[FM1_RESAMPLER_LP_LEN - 2 - j]);
    y2 += h[j + 2] * (e[j + 2] + e[FM1_RESAMPLER_LP_LEN - 3 - j]);
    y3 += h[j + 3] * (e[j + 3] + e[FM1_RESAMPLER_LP_LEN - 4 - j]);
  }
  for (; j < FM1_RESAMPLER_LP_PAIRS; ++j) y0 += h[j] * (e[j] + e[FM1_RESAMPLER_LP_LEN - 1 - j]);
  return ((y0 + y1) + (y2 + y3)) + h[FM1_RESAMPLER_LP_PAIRS] * e[FM1_RESAMPLER_LP_PAIRS];
}

/* Array form: takes inputs from in[0..n_in) as outputs need them and writes
 * up to max_out outputs; returns how many it wrote, and stores how many
 * inputs it took in *n_used (when not NULL). Stops early when the input runs
 * out; what it took is kept for the next call. */
static inline uint32_t fm1_resampler_process(fm1_resampler_t *r, const float *in, uint32_t n_in,
                                             uint32_t *n_used, float *out, uint32_t max_out) {
  uint32_t used = 0, made = 0;
  while (made < max_out) {
    if (used < n_in) used += fm1_resampler_push(r, in + used, n_in - used);
    if (fm1_resampler_needed(r)) break;
    out[made++] = fm1_resampler_pop(r);
  }
  if (n_used) *n_used = used;
  return made;
}

/* Group delay in output samples: 0 for pass-through and for the 51/47 fast
 * path (output k is input time k x 51 / 47), else FM1_RESAMPLER_DELAY = 30
 * (output k is the signal at input time (k - 30) / out_rate; input 0 is
 * time 0). */
static inline float fm1_resampler_delay(const fm1_resampler_t *r) {
  return r->mode == FM1_RESAMPLER_CONVERT && !r->poly ? (float)FM1_RESAMPLER_DELAY : 0.0f;
}

