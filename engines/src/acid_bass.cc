// acid_bass.cc -- "Acid Bass", a monophonic bass after the TB-303: the 303
// bass of fm1-x0x (Charles Vestal, GPL-3.0-only), vendored with two small
// local changes in third_party/fm1-x0x/ (UPSTREAM.md), behind engine API v3.
// It links GPL code, so it is built only while the GPL switch is on
// (FM1_GPL_MODS, engines/Makefile; mk/fm1-x0x.mk) and listed GPL in the
// licence table (src/registry.cc).
//
// What fm1-x0x's bass is (third_party/fm1-x0x/dsp/bass303.h has the detail):
// Open303's signal path by Robin Schmidt (MIT), statement for statement, with
// a polyBLEP saw and the 303's tanh-shaped square, 2x oversampling, controls
// every 4 samples, the Devilfish ranges for slide and accent decay after
// jc303 (midilab, GPL-3.0), and a Soft or RAT drive after schwung-303's (the
// RAT after dm-Rat, Dave Mollen, GPL-3.0). schwung-303 (Charles Vestal) is
// the port it came through. Every instance is self-contained.
//
// What this file adds, and how it plays (engines/README.md, "Acid Bass"):
//   - Notes, as Open303's MIDI handling and schwung-303 play them. A key
//     list, newest last (16 keys). A note-on with no key held triggers the
//     note; one played while another is held slides to it without
//     restarting the envelopes (legato is the 303's slide), at the Slide
//     time. Letting go of the newest key while older ones are held slides
//     back to the newest of them; letting go of the last releases. A
//     velocity of 100 or more is an accent (schwung-303's rule, which
//     TB-3PO's 118 and 72 meet); velocity does nothing else, as on the 303.
//   - The rate: the host's own, 40-96 kHz (the vendored bass reads the
//     instance's rate where upstream reads 44,100; at 44.1 kHz it computes
//     upstream's samples). Hosts outside that are refused.
//   - A grid of 16 samples. The vendored bass's output depends on where
//     its render calls split, so it renders whole 16-sample chunks, counted
//     from create, and the host's frames are handed out of the last chunk.
//     A note, a bend or a parameter lands on the next chunk (0.36 ms at
//     44,118 Hz), so the output is the same at any host block size and any
//     split of a block. A chunk is the control block of the SMOOTH ramps.
//   - Parameters in their own units (Hz, %, ms), as floats, not 7-bit pots:
//     each reaches the vendored bass as a pot position between the integers
//     (bass303_set_value, a local change). The mapping is X0X's: Cutoff
//     314-2,394 Hz and Decay 200-2,000 ms exponential, Slide 2-360 ms and
//     Acc Decay 30-3,000 ms linear in the pot.
//   - Pitch outside the vendored bass: Tune, the bend and the voice's
//     per-note pitch offset multiply the oscillator's target and its slewed
//     frequency alike, so a bend moves the note at once and a slide in
//     progress goes on from where it is. With all three at 0 nothing is
//     multiplied: the vendored bass's own pitch, bit for bit.
//   - Volume outside it too: the vendored bass keeps X0X's default level
//     (its Volume pot at 96, -14.6 dB, so the drive sees the level X0X
//     tuned it at), and Volume scales its output by (Volume / 0.7)^2, so the
//     default, 0.7, is X0X's output exactly and 1 is 6.2 dB louder.
//   - Flags. Cutoff, Resonance, Env Mod, Tune, Volume, Drive and Slide are
//     read continuously: SMOOTH (a ramp over 2.5 ms, 7 chunks at 44,118 Hz,
//     while a note sounds) and MOD; Cutoff and Slide LOG. Decay, Accent and
//     Acc Decay are read at a note-on, slides included, as in Open303:
//     LATCH. Wave and Drive Type would click mid-note, so they wait for the
//     next note that is not a slide (LATCH and MOD: a route is rounded);
//     while nothing sounds they apply at once. Cutoff, Resonance, Env Mod,
//     Drive and Volume are POLY: the voice keeps an offset for each, and one
//     for its pitch, which restart at 0 whenever it moves to another key
//     (a trigger, a slide or a slide back) and end with it.
//
// No allocation and no libm: the vendored bass has its own maths
// (fastmath.h), and the wrapper's exp2 and log2 are fm1_math.h's, so every
// build computes the same bits.
//
// MIT licence (this file); the program it is linked into is GPL-3.0 while
// the vendored bass is in it.

