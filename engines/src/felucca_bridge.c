/* felucca_bridge.c -- the C side of the Felucca shim (felucca_bridge.h).
 *
 * Includes Felucca's own files, unmodified (third_party/felucca/src, and
 * gen/felucca_tables.h, the output of its tools/gen_tables.py), the way
 * Felucca's felucca.c includes them: the tables, core.h, dsp.c, then the
 * engines. Two definitions are made around core.h, neither of which
 * changes what the engines compute:
 *   - core.h's last line puts a boot-loop record in a ".noinit" section,
 *     which only the FM-1's linker script has (Mach-O cannot even name it).
 *     `section` is defined to `unused` for that line, and the record is
 *     renamed, so it is a plain unused variable here;
 *   - core.h defines the four parts, trk[4]. Our instances each hold one
 *     part of their own, so `trk` is defined, after core.h, as the part the
 *     current call works on. An engine that finds its part as `t - trk`
 *     (WHEEL, for its arrays below) then finds part 0.
 * WHEEL keeps its per-part and per-voice state in static arrays of its own
 * (eng_wheel.c, drw_t and drw_v). The world holds a copy of part 0's, which
 * the bridge copies into those arrays at the start of each call that runs
 * WHEEL code and back at its end: 832 bytes each way, once a control block
 * and once a note-on [verified: tools/jieli/sizes_felucca.c, 96 + 8 x 92
 * bytes on pi32v2, i386 and x86-64]. The arrays themselves are sized for
 * Felucca's four parts, 3,328 bytes of static RAM of which part 0's are used.
 * The audio task is the only caller (fm1_engine.h, "Threads").
 *
 * Above the engines this file does what Felucca's voice.c does for a voice,
 * in our own code: the envelope (attack, decay to the sustain level and
 * release, at the control rate, on Felucca's tables, as its env_tick), the
 * modulation an engine reads (vmod_t: the amplitude ramp, the pitch, the
 * cutoff with the envelope amount and the accent, the shape), and the
 * retrigger of a sounding voice (the attack from where the level is, the
 * phases kept). Voice allocation, glide and parameters are the shim's.
 *
 * Integer arithmetic throughout, as Felucca's: every build gives the same
 * bits. Compiled with -fwrapv (mk/felucca.mk): the engines multiply and
 * shift signed values as Felucca's own builds do.
 *
 * Built only while the GPL switch is on (FM1_GPL_MODS, engines/Makefile;
 * mk/felucca.mk): the object holds GPL-3.0-only code. MIT licence (this
 * file's own text).
 */
