static unsigned glyph_index(char c)
{
    unsigned i;
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (i = 0; charset[i]; ++i)
        if (charset[i] == c) return i;
    return 0;
}

static unsigned length(const char *s, unsigned limit)
{
    unsigned n = 0;
    while (s && n < limit && s[n]) ++n;
    return n;
}

/* Is (x, y) lit by text `s` (n chars), centred, top row `top`, at `scale`?
 * Cells are 6 x 8 glyph pixels: 5 x 7 plus one blank column. */
static int text(const char *s, unsigned n, unsigned x, unsigned y,
                unsigned top, unsigned scale)
{
    unsigned width, left, cell, column, row;
    if (!n || y < top || y >= top + 7u * scale) return 0;
    width = n * 6u * scale - scale;
    left = (LUNAR_M5_WIDTH - width) / 2u;
    if (x < left || x >= left + width) return 0;
    cell = (x - left) / scale;
    column = cell % 6u;
    if (column == 5u) return 0;
    row = (y - top) / scale;
    return (glyphs[glyph_index(s[cell / 6u])][row] >> (4u - column)) & 1u;
}

unsigned lunar_m5_pixel(unsigned x, unsigned y, const char *build_id)
{
    static const unsigned short bars[8] = {
        0xffff, 0xffe0, 0x07ff, 0x07e0, 0xf81f, 0xf800, 0x001f, 0x0000
    };
    if (x >= LUNAR_M5_WIDTH || y >= LUNAR_M5_HEIGHT) return 0;
    if (!x || !y || x == LUNAR_M5_WIDTH - 1u || y == LUNAR_M5_HEIGHT - 1u) return WHITE;
    if (y >= BARS_TOP) return bars[x / 30u];
    if (text("LUNAR M5", 8u, x, y, 14u, 3u)) return WHITE;
    if (text(build_id, length(build_id, LUNAR_M5_ID_MAX), x, y, 52u, 2u)) return YELLOW;
    if (text("TEST PATTERN", 12u, x, y, 82u, 2u)) return CYAN;
    return BACKGROUND;
}

enum lunar_panel_result lunar_panel_m5_pattern(const struct lunar_panel_transport *bus,
                                               const char *build_id)
{
    unsigned x, y;
    int success;
    enum lunar_panel_result result = lunar_panel_setup(bus);
    if (result != LUNAR_PANEL_OK) return result;
    success = bus->begin(bus->context, 0x2c);
    for (y = 0; success && y < LUNAR_M5_HEIGHT; ++y) {
        for (x = 0; success && x < LUNAR_M5_WIDTH; ++x) {
            unsigned word = lunar_m5_pixel(x, y, build_id);
            success = bus->write(bus->context, (unsigned char)(word >> 8));
            if (success) success = bus->write(bus->context, (unsigned char)word);
        }
    }
    bus->end(bus->context);
    if (!success) return LUNAR_PANEL_TRANSFER_FAILED;
    if (!lunar_panel_command(bus, 0x29)) return LUNAR_PANEL_TRANSFER_FAILED;
    return LUNAR_PANEL_OK;
}
