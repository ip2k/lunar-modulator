#!/usr/bin/env python3
"""Generate firmware/m6/m6_sine.h, the M6 RAM image's quarter-wave sine.

    python3 tools/m6_tables.py            # rewrite firmware/m6/m6_sine.h
    python3 tools/m6_tables.py --check    # exit 1 if it is stale

The table is the first quarter (points 0..1023) of the trunc12 sine
kSinTab12 (tools/msfa_tables.py, engines/src/msfa_rom.cc): 4,096 Q15 points
of one cycle, each the value at the middle of its step. Because each point
sits at a step's middle, the cycle is exactly symmetric:
point 2047 - i equals point i, and point i + 2048 is minus point i. So the
quarter rebuilds all 4,096 points bit for bit (tests/test_m6_image.py checks
it against kSinTab12 parsed from msfa_rom.cc), in 2,048 bytes instead of
8,192, which the 16 KiB RAM image needs. MIT, like msfa_tables.py.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from msfa_tables import sin12_table  # noqa: E402

OUT = ROOT / "firmware" / "m6" / "m6_sine.h"
QUARTER = 1024


def quarter() -> list[int]:
    return sin12_table()[:QUARTER]


def source() -> str:
    rows = []
    values = quarter()
    for i in range(0, QUARTER, 12):
        rows.append("    " + ", ".join(str(v) for v in values[i:i + 12]) + ",")
    body = "\n".join(rows)
    return f"""\
/* SPDX-License-Identifier: MIT
 * m6_sine.h -- generated by tools/m6_tables.py; do not edit.
 * The first quarter (points 0..1023) of the trunc12 sine kSinTab12
 * (engines/src/msfa_rom.cc): Q15, each point the sine at the middle of its
 * step, 2 pi (i + 1/2) / 4096. lunar_m6_sine (m6_core.c) rebuilds the other
 * three quarters by symmetry, bit for bit.
 */
#ifndef LUNAR_M6_SINE_H
#define LUNAR_M6_SINE_H
static const short lunar_m6_sine_quarter[{QUARTER}] = {{
{body}
}};
#endif
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the header is stale")
    args = parser.parse_args()
    text = source()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/m6_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
